using System.Xml.Linq;

namespace Svg2Gfx;

public sealed class GeneratorOptions
{
    public required string FunctionName;
    public string SourceName = "";
    public double Dpi = 96;
    public int? Precision;
    public bool Comments = true;
}

/// <summary>A fill or stroke after resolving currentColor, url(#...) and fallbacks against a shape.</summary>
internal sealed class ResolvedPaint
{
    public static readonly ResolvedPaint None = new() { Kind = PaintKind.None };
    public PaintKind Kind;           // None, Color or Url (gradient)
    public Rgba Color;
    public bool Linear;
    public string Spread = "pad";
    public Matrix Transform = Matrix.Identity;
    public double X1, Y1, X2, Y2;    // linear
    public double Cx, Cy, R, Fx, Fy, Fr; // radial
    public List<GradientStop> Stops = new();
}

/// <summary>Walks an SVG document and emits a gfx::canvas drawing routine.</summary>
public sealed class Generator
{
    public static readonly XNamespace SvgNs = "http://www.w3.org/2000/svg";

    private readonly RenderContext _ctx = new();
    private readonly CppWriter _w = new();
    private readonly Dictionary<string, string> _state = new(); // last emitted setter per canvas property
    private int _shapeCount;
    private GeneratorOptions _opt = null!;

    public IReadOnlyList<string> Warnings => _ctx.Warnings;

    public string Generate(XDocument doc, GeneratorOptions opt)
    {
        _opt = opt;
        _w.Precision = opt.Precision;
        _ctx.Dpi = opt.Dpi;
        var root = doc.Root ?? throw new InvalidDataException("empty document");
        if (root.Name.LocalName != "svg") throw new InvalidDataException("root element is not <svg>");

        foreach (var e in doc.Descendants())
        {
            var id = (string?)e.Attribute("id");
            if (!string.IsNullOrEmpty(id)) _ctx.Ids.TryAdd(id, e);
        }
        foreach (var style in doc.Descendants().Where(e => e.Name.LocalName == "style" && IsSvg(e)))
        {
            var type = (string?)style.Attribute("type");
            if (type != null && type.Trim() != "text/css") continue;
            Css.ParseStylesheet(style.Value, _ctx.Rules, _ctx.Warnings);
        }
        _ctx.Styles = new StyleResolver(_ctx);

        // --- sizing (intrinsic size, viewBox and preserveAspectRatio) ---
        var rootStyle = _ctx.Styles.Compute(root, new ComputedStyle());
        double width = RootLength(root, "width", rootStyle);
        double height = RootLength(root, "height", rootStyle);
        double vbx = 0, vby = 0, vbw = 0, vbh = 0;
        var vb = Scanner.ParseNumberList((string?)root.Attribute("viewBox") ?? "");
        bool hasViewBox = vb != null && vb.Count == 4 && vb[2] > 0 && vb[3] > 0;
        if (vb != null && vb.Count > 0 && !hasViewBox) _ctx.Warn("invalid viewBox ignored");
        if (hasViewBox) { vbx = vb![0]; vby = vb[1]; vbw = vb[2]; vbh = vb[3]; }
        if (width <= 0 || height <= 0)
        {
            if (hasViewBox)
            {
                double ratio = vbw / vbh;
                if (width <= 0 && height > 0) width = height * ratio;
                else if (width > 0 && height <= 0) height = width / ratio;
                else { width = vbw; height = vbh; }
            }
            else
            {
                if (width <= 0) width = 300;
                if (height <= 0) height = 150;
            }
        }
        _ctx.ViewportWidth = hasViewBox ? vbw : width;
        _ctx.ViewportHeight = hasViewBox ? vbh : height;
        var view = hasViewBox ? ViewBoxMatrix(vbx, vby, vbw, vbh, width, height, (string?)root.Attribute("preserveAspectRatio")) : Matrix.Identity;
        var rootCtm = LocalTransform(root).Then(view);

        // --- body ---
        _w.Indent();
        foreach (var child in root.Elements()) Walk(child, rootStyle, rootCtm);
        _w.Outdent();
        string body = _w.ToString();
        var defBase = opt.FunctionName.ToUpperInvariant();
        // --- assemble the routine ---
        var o = new CppWriter { Precision = opt.Precision };
        o.Line($"// Generated by svg2gfx from {CppWriter.Comment(opt.SourceName)}");
        o.Line($"#pragma once");
        o.Line("#include <gfx.hpp>");
        o.Line("");
        o.Line($"// Intrinsic size: {width.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture)} x {height.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture)}, {_shapeCount} shape(s)");
        o.Line($"constexpr gfx::sizef {opt.FunctionName}_dimensions({o.F(width)}, {o.F(height)});");
        foreach (var wmsg in _ctx.Warnings) o.Line($"// warning: {CppWriter.Comment(wmsg)}");
        o.Line("template <typename Destination>");
        o.Line($"gfx::gfx_result {opt.FunctionName}(Destination& destination, gfx::spoint16 location = gfx::spoint16(0, 0), const gfx::matrix& transform = gfx::matrix::create_identity()) {{");
        o.Indent();
        // The canvas is bound at (0,0) and covers the destination; `location` is folded into the
        // transform. gfx's draw::canvas() clips incorrectly when bound at a non-zero location
        // (direct and callback modes disagree about the offset), so that path is avoided.
        o.Line("const gfx::size16 canvas_size = destination.dimensions();");
        o.Line("if (canvas_size.width == 0 || canvas_size.height == 0) return gfx::gfx_result::success;");
        o.Line("gfx::canvas cvs(canvas_size);");
        o.Line("gfx::gfx_result res = cvs.initialize();");
        o.Line("if (res != gfx::gfx_result::success) return res;");
        o.Line("res = gfx::draw::canvas(destination, cvs);");
        o.Line("if (res != gfx::gfx_result::success) return res;");
        o.Line("gfx::matrix xform(transform);");
        o.Line("xform *= gfx::matrix::create_translate((float)location.x, (float)location.y);");
        string head = o.ToString();
        var tail = new CppWriter();
        tail.Indent();
        tail.Line("return gfx::gfx_result::success;");
        tail.Outdent();
        tail.Line("}");
        return head + body + tail;
    }

    private static bool IsSvg(XElement e) => e.Name.Namespace == SvgNs || e.Name.Namespace == XNamespace.None;

    private double RootLength(XElement root, string name, ComputedStyle style)
    {
        var a = (string?)root.Attribute(name);
        if (a == null || a.Trim() == "auto") return 0;
        if (!SvgLength.TryParse(a, out var l) || l.Unit == LengthUnit.Percent) return 0;
        return l.Resolve(_ctx, LengthAxis.Other, style.FontSize);
    }

    private static Matrix ViewBoxMatrix(double vbx, double vby, double vbw, double vbh, double width, double height, string? par)
    {
        double sx = width / vbw, sy = height / vbh;
        string align = "xMidYMid";
        bool slice = false;
        if (par != null)
        {
            var parts = par.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries).Where(p => p != "defer").ToArray();
            if (parts.Length > 0) align = parts[0];
            if (parts.Length > 1) slice = parts[1] == "slice";
        }
        if (align == "none")
            return Matrix.Translate(-vbx, -vby).Then(Matrix.Scale(sx, sy));
        double scale = slice ? Math.Max(sx, sy) : Math.Min(sx, sy);
        double tx = -vbx * scale, ty = -vby * scale;
        double extraX = width - vbw * scale, extraY = height - vbh * scale;
        if (align.Contains("xMid")) tx += extraX / 2; else if (align.Contains("xMax")) tx += extraX;
        if (align.Contains("YMid")) ty += extraY / 2; else if (align.Contains("YMax")) ty += extraY;
        return Matrix.Scale(scale, scale).Then(Matrix.Translate(tx, ty));
    }

    private Matrix LocalTransform(XElement e)
    {
        var t = (string?)e.Attribute("transform");
        if (t == null) return Matrix.Identity;
        if (SvgTransform.TryParse(t, out var m)) return m;
        _ctx.Warn($"<{e.Name.LocalName}>: invalid transform '{t}' ignored");
        return Matrix.Identity;
    }

    private string Describe(XElement e)
    {
        var id = (string?)e.Attribute("id");
        var cls = (string?)e.Attribute("class");
        string s = "<" + e.Name.LocalName;
        if (id != null) s += $" id=\"{id}\"";
        if (cls != null) s += $" class=\"{cls}\"";
        return CppWriter.Comment(s + ">");
    }

    private void Walk(XElement e, ComputedStyle parentStyle, Matrix parentCtm)
    {
        if (!IsSvg(e)) return; // editor metadata (inkscape:, sodipodi:, ...)
        string name = e.Name.LocalName;
        switch (name)
        {
            case "g":
            case "a":
            {
                var style = _ctx.Styles.Compute(e, parentStyle);
                if (!style.Display) return;
                WarnIgnoredEffects(e);
                var ctm = LocalTransform(e).Then(parentCtm);
                foreach (var child in e.Elements()) Walk(child, style, ctm);
                return;
            }
            case "path":
            case "rect":
            case "circle":
            case "ellipse":
            case "line":
            case "polyline":
            case "polygon":
                RenderShape(e, parentStyle, parentCtm);
                return;
            case "defs":
            case "linearGradient":
            case "radialGradient":
            case "stop":
            case "style":
            case "title":
            case "desc":
            case "metadata":
            case "symbol":
                return; // never rendered directly
            case "clipPath":
            case "mask":
            case "pattern":
            case "marker":
            case "filter":
                return; // definitions; references to them are reported where used
            default:
                _ctx.Warn($"<{name}> is not supported and was skipped");
                if (_opt.Comments) _w.Line($"// skipped unsupported {Describe(e)}");
                return;
        }
    }

    private void WarnIgnoredEffects(XElement e)
    {
        foreach (var attr in new[] { "clip-path", "mask", "filter" })
        {
            var v = (string?)e.Attribute(attr);
            if (v != null && v.Trim() != "none")
                _ctx.Warn($"{attr} is not supported and was ignored (on {Describe(e)})");
        }
    }

    private SvgLength? Len(XElement e, string name)
    {
        var a = (string?)e.Attribute(name);
        if (a == null) return null;
        if (SvgLength.TryParse(a, out var l)) return l;
        if (a.Trim() != "auto") _ctx.Warn($"<{e.Name.LocalName}>: invalid {name} '{a}' ignored");
        return null;
    }

    private double L(XElement e, string name, LengthAxis axis, ComputedStyle s, double def = 0) =>
        Len(e, name)?.Resolve(_ctx, axis, s.FontSize) ?? def;

    private Geometry? BuildGeometry(XElement e, ComputedStyle s)
    {
        switch (e.Name.LocalName)
        {
            case "path":
            {
                var g = PathData.Parse((string?)e.Attribute("d"), out var err);
                if (err != null) _ctx.Warn($"{Describe(e)}: path data error ({err}); rendered up to the error");
                return g.HasDrawing ? g : null;
            }
            case "rect":
            {
                double x = L(e, "x", LengthAxis.X, s), y = L(e, "y", LengthAxis.Y, s);
                double w = L(e, "width", LengthAxis.X, s), h = L(e, "height", LengthAxis.Y, s);
                if (w <= 0 || h <= 0) return null;
                double? rxo = Len(e, "rx")?.Resolve(_ctx, LengthAxis.X, s.FontSize);
                double? ryo = Len(e, "ry")?.Resolve(_ctx, LengthAxis.Y, s.FontSize);
                if (rxo < 0) rxo = null; if (ryo < 0) ryo = null;
                double rx = rxo ?? ryo ?? 0, ry = ryo ?? rxo ?? 0;
                rx = Math.Min(rx, w / 2); ry = Math.Min(ry, h / 2);
                return RectPath(x, y, w, h, rx, ry);
            }
            case "circle":
            {
                double r = L(e, "r", LengthAxis.Other, s);
                if (r <= 0) return null;
                return new EllipseGeometry { Cx = L(e, "cx", LengthAxis.X, s), Cy = L(e, "cy", LengthAxis.Y, s), Rx = r, Ry = r };
            }
            case "ellipse":
            {
                double? rxo = Len(e, "rx")?.Resolve(_ctx, LengthAxis.X, s.FontSize);
                double? ryo = Len(e, "ry")?.Resolve(_ctx, LengthAxis.Y, s.FontSize);
                double rx = rxo ?? ryo ?? 0, ry = ryo ?? rxo ?? 0;
                if (rx <= 0 || ry <= 0) return null;
                return new EllipseGeometry { Cx = L(e, "cx", LengthAxis.X, s), Cy = L(e, "cy", LengthAxis.Y, s), Rx = rx, Ry = ry };
            }
            case "line":
            {
                var g = new PathGeometry();
                double x1 = L(e, "x1", LengthAxis.X, s), y1 = L(e, "y1", LengthAxis.Y, s);
                double x2 = L(e, "x2", LengthAxis.X, s), y2 = L(e, "y2", LengthAxis.Y, s);
                g.MoveTo(x1, y1, x1, y1);
                g.LineTo(x2, y2, x1, y1);
                return g;
            }
            case "polyline":
            case "polygon":
            {
                var pts = Scanner.ParseNumberList((string?)e.Attribute("points") ?? "");
                if (pts == null)
                {
                    // per spec, render the points up to the error
                    pts = new List<double>();
                    var sc = new Scanner((string?)e.Attribute("points") ?? "");
                    while (sc.TryNumber(out var v)) { pts.Add(v); sc.SkipCommaWsp(); }
                    _ctx.Warn($"{Describe(e)}: bad points list; rendered up to the error");
                }
                if (pts.Count % 2 == 1) pts.RemoveAt(pts.Count - 1);
                if (pts.Count < 4) return null;
                var g = new PathGeometry();
                g.MoveTo(pts[0], pts[1], pts[0], pts[1]);
                for (int i = 2; i < pts.Count; i += 2) g.LineTo(pts[i], pts[i + 1], pts[i - 2], pts[i - 1]);
                if (e.Name.LocalName == "polygon") g.Close();
                return g;
            }
        }
        return null;
    }

    private static PathGeometry RectPath(double x, double y, double w, double h, double rx, double ry)
    {
        var g = new PathGeometry();
        if (rx <= 0 || ry <= 0)
        {
            g.MoveTo(x, y, x, y);
            g.LineTo(x + w, y, x, y);
            g.LineTo(x + w, y + h, x + w, y);
            g.LineTo(x, y + h, x + w, y + h);
            g.Close();
            return g;
        }
        const double k = 0.5522847498307936; // cubic approximation of a quarter ellipse
        double kx = rx * k, ky = ry * k, r = x + w, b = y + h;
        g.MoveTo(x + rx, y, x + rx, y);
        g.LineTo(r - rx, y, x + rx, y);
        g.CubicTo(r - rx + kx, y, r, y + ry - ky, r, y + ry, r - rx, y);
        g.LineTo(r, b - ry, r, y + ry);
        g.CubicTo(r, b - ry + ky, r - rx + kx, b, r - rx, b, r, b - ry);
        g.LineTo(x + rx, b, r - rx, b);
        g.CubicTo(x + rx - kx, b, x, b - ry + ky, x, b - ry, x + rx, b);
        g.LineTo(x, y + ry, x, b - ry);
        g.CubicTo(x, y + ry - ky, x + rx - kx, y, x + rx, y, x, y + ry);
        g.Close();
        return g;
    }

    private ResolvedPaint ResolvePaint(Paint p, ComputedStyle s, Bounds bounds, XElement e, string prop)
    {
        switch (p.Kind)
        {
            case PaintKind.None: return ResolvedPaint.None;
            case PaintKind.Color: return new ResolvedPaint { Kind = PaintKind.Color, Color = p.Color };
            case PaintKind.CurrentColor: return new ResolvedPaint { Kind = PaintKind.Color, Color = s.Color };
        }
        var g = Gradients.Resolve(_ctx, p.Url!);
        if (g == null)
        {
            if (_ctx.Ids.TryGetValue(p.Url!, out var target))
                _ctx.Warn($"{prop}: paint server <{target.Name.LocalName} id=\"{p.Url}\"> is not supported");
            else
                _ctx.Warn($"{prop}: url(#{p.Url}) does not reference anything");
            return p.Fallback != null ? ResolvePaint(p.Fallback, s, bounds, e, prop) : ResolvedPaint.None;
        }
        if (g.Stops.Count == 0) return ResolvedPaint.None;
        if (g.Stops.Count == 1) return new ResolvedPaint { Kind = PaintKind.Color, Color = g.Stops[0].Color };
        var rp = new ResolvedPaint { Kind = PaintKind.Url, Linear = g.Linear, Spread = g.Spread, Stops = g.Stops };
        if (g.ObjectBoundingBox)
        {
            // a zero-width or zero-height bounding box disables objectBoundingBox paint
            if (bounds.Width <= 0 || bounds.Height <= 0) return ResolvedPaint.None;
            var bbox = Matrix.Scale(bounds.Width, bounds.Height).Then(Matrix.Translate(bounds.MinX, bounds.MinY));
            rp.Transform = g.Transform.Then(bbox);
            rp.X1 = g.X1.AsFraction(); rp.Y1 = g.Y1.AsFraction(); rp.X2 = g.X2.AsFraction(); rp.Y2 = g.Y2.AsFraction();
            rp.Cx = g.Cx.AsFraction(); rp.Cy = g.Cy.AsFraction(); rp.R = g.R.AsFraction(); rp.Fr = g.Fr.AsFraction();
            rp.Fx = g.Fx?.AsFraction() ?? rp.Cx; rp.Fy = g.Fy?.AsFraction() ?? rp.Cy;
        }
        else
        {
            double fs = s.FontSize;
            rp.Transform = g.Transform;
            rp.X1 = g.X1.Resolve(_ctx, LengthAxis.X, fs); rp.Y1 = g.Y1.Resolve(_ctx, LengthAxis.Y, fs);
            rp.X2 = g.X2.Resolve(_ctx, LengthAxis.X, fs); rp.Y2 = g.Y2.Resolve(_ctx, LengthAxis.Y, fs);
            rp.Cx = g.Cx.Resolve(_ctx, LengthAxis.X, fs); rp.Cy = g.Cy.Resolve(_ctx, LengthAxis.Y, fs);
            rp.R = g.R.Resolve(_ctx, LengthAxis.Other, fs); rp.Fr = g.Fr.Resolve(_ctx, LengthAxis.Other, fs);
            rp.Fx = g.Fx?.Resolve(_ctx, LengthAxis.X, fs) ?? rp.Cx; rp.Fy = g.Fy?.Resolve(_ctx, LengthAxis.Y, fs) ?? rp.Cy;
        }
        if (!g.Linear && rp.R <= 0) return new ResolvedPaint { Kind = PaintKind.Color, Color = g.Stops[^1].Color };
        return rp;
    }

    /// <summary>Emits a setter only when it differs from what the canvas already holds.</summary>
    private void Set(string key, string statement)
    {
        if (_state.TryGetValue(key, out var prev) && prev == statement) return;
        _state[key] = statement;
        _w.Line(statement);
    }

    private void EmitGradient(string prefix, ResolvedPaint p)
    {
        _w.Line($"gfx::gradient_stop {prefix}_stops[] = {{");
        _w.Indent();
        foreach (var st in p.Stops) _w.Line($"{{{_w.F(st.Offset)}, {st.Color.ToCpp()}}},");
        _w.Outdent();
        _w.Line("};");
        _w.Line($"gfx::gradient {prefix}_gradient;");
        _w.Line($"{prefix}_gradient.type = gfx::gradient_type::{(p.Linear ? "linear" : "radial")};");
        _w.Line($"{prefix}_gradient.spread = gfx::spread_method::{p.Spread};");
        _w.Line($"{prefix}_gradient.transform = {(p.Transform.IsIdentity ? "gfx::matrix::create_identity()" : _w.Mat(p.Transform))};");
        if (p.Linear)
        {
            _w.Line($"{prefix}_gradient.linear.x1 = {_w.F(p.X1)};");
            _w.Line($"{prefix}_gradient.linear.y1 = {_w.F(p.Y1)};");
            _w.Line($"{prefix}_gradient.linear.x2 = {_w.F(p.X2)};");
            _w.Line($"{prefix}_gradient.linear.y2 = {_w.F(p.Y2)};");
        }
        else
        {
            _w.Line($"{prefix}_gradient.radial.cx = {_w.F(p.Cx)};");
            _w.Line($"{prefix}_gradient.radial.cy = {_w.F(p.Cy)};");
            _w.Line($"{prefix}_gradient.radial.fx = {_w.F(p.Fx)};");
            _w.Line($"{prefix}_gradient.radial.fy = {_w.F(p.Fy)};");
            _w.Line($"{prefix}_gradient.radial.cr = {_w.F(p.R)};");
            _w.Line($"{prefix}_gradient.radial.fr = {_w.F(p.Fr)};");
        }
        _w.Line($"{prefix}_gradient.stops = {prefix}_stops;");
        _w.Line($"{prefix}_gradient.stops_size = {p.Stops.Count};");
        // fill_gradient()/stroke_gradient() also switch the paint type to gradient
        _w.Line($"cvs.{prefix}_gradient({prefix}_gradient);");
        _state[$"{prefix}_paint_type"] = $"cvs.{prefix}_paint_type(gfx::paint_type::gradient);";
    }

    private void RenderShape(XElement e, ComputedStyle parentStyle, Matrix parentCtm)
    {
        var s = _ctx.Styles.Compute(e, parentStyle);
        if (!s.Display) return;
        WarnIgnoredEffects(e);
        var ctm = LocalTransform(e).Then(parentCtm);
        var geo = BuildGeometry(e, s);
        if (geo == null || !s.Visible) return;
        var bounds = geo.GetBounds();
        var fill = ResolvePaint(s.Fill, s, bounds, e, "fill");
        var stroke = s.StrokeWidth > 0 ? ResolvePaint(s.Stroke, s, bounds, e, "stroke") : ResolvedPaint.None;
        double fillOpacity = s.FillOpacity * s.Opacity, strokeOpacity = s.StrokeOpacity * s.Opacity;
        if (fillOpacity <= 0) fill = ResolvedPaint.None;
        if (strokeOpacity <= 0) stroke = ResolvedPaint.None;
        if (fill.Kind == PaintKind.None && stroke.Kind == PaintKind.None) return;

        ++_shapeCount;
        if (_opt.Comments) _w.Line($"// {Describe(e)}");
        _w.Line("{");
        _w.Indent();
        Set("transform", ctm.IsIdentity ? "cvs.transform(xform);" : $"cvs.transform({_w.Mat(ctm)} * xform);");

        // fill
        switch (fill.Kind)
        {
            case PaintKind.None:
                Set("fill_paint_type", "cvs.fill_paint_type(gfx::paint_type::none);");
                break;
            case PaintKind.Color:
                Set("fill_paint_type", "cvs.fill_paint_type(gfx::paint_type::solid);");
                Set("fill_color", $"cvs.fill_color({fill.Color.ToCpp()});");
                break;
            case PaintKind.Url:
                EmitGradient("fill", fill);
                break;
        }
        if (fill.Kind != PaintKind.None)
        {
            Set("fill_opacity", $"cvs.fill_opacity({_w.F(fillOpacity)});");
            Set("fill_rule", $"cvs.fill_rule(gfx::fill_rule::{s.FillRule});");
        }

        // stroke
        switch (stroke.Kind)
        {
            case PaintKind.None:
                Set("stroke_paint_type", "cvs.stroke_paint_type(gfx::paint_type::none);");
                break;
            case PaintKind.Color:
                Set("stroke_paint_type", "cvs.stroke_paint_type(gfx::paint_type::solid);");
                Set("stroke_color", $"cvs.stroke_color({stroke.Color.ToCpp()});");
                break;
            case PaintKind.Url:
                EmitGradient("stroke", stroke);
                break;
        }
        if (stroke.Kind != PaintKind.None)
        {
            Set("stroke_opacity", $"cvs.stroke_opacity({_w.F(strokeOpacity)});");
            Set("stroke_width", $"cvs.stroke_width({_w.F(s.StrokeWidth)});");
            Set("stroke_line_cap", $"cvs.stroke_line_cap(gfx::line_cap::{s.LineCap});");
            Set("stroke_line_join", $"cvs.stroke_line_join(gfx::line_join::{s.LineJoin});");
            Set("stroke_miter_limit", $"cvs.stroke_miter_limit({_w.F(s.MiterLimit)});");
            if (s.Dash != null)
            {
                _w.Line($"float dash_values[] = {{{string.Join(", ", s.Dash.Select(_w.F))}}};");
                _w.Line($"cvs.stroke_dash(gfx::dash{{{_w.F(s.DashOffset)}, dash_values, {s.Dash.Length}}});");
                _state["stroke_dash"] = "<dashed>";
            }
            else
            {
                Set("stroke_dash", "cvs.stroke_dash(gfx::dash{0.f, nullptr, 0});");
            }
        }

        // geometry
        switch (geo)
        {
            case EllipseGeometry el when el.IsCircle:
                _w.Checked($"cvs.circle({_w.Pt(el.Cx, el.Cy)}, {_w.F(el.Rx)})");
                break;
            case EllipseGeometry el:
                _w.Checked($"cvs.ellipse({_w.Pt(el.Cx, el.Cy)}, gfx::sizef({_w.F(el.Rx)}, {_w.F(el.Ry)}))");
                break;
            case PathGeometry pg:
                foreach (var seg in pg.Segs)
                {
                    switch (seg.Kind)
                    {
                        case SegKind.Move: _w.Checked($"cvs.move_to({_w.Pt(seg.X, seg.Y)})"); break;
                        case SegKind.Line: _w.Checked($"cvs.line_to({_w.Pt(seg.X, seg.Y)})"); break;
                        case SegKind.Quad: _w.Checked($"cvs.quad_to({_w.Pt(seg.X1, seg.Y1)}, {_w.Pt(seg.X, seg.Y)})"); break;
                        case SegKind.Cubic: _w.Checked($"cvs.cubic_to({_w.Pt(seg.X1, seg.Y1)}, {_w.Pt(seg.X2, seg.Y2)}, {_w.Pt(seg.X, seg.Y)})"); break;
                        case SegKind.Arc:
                            _w.Checked($"cvs.arc_to(gfx::sizef({_w.F(seg.Rx)}, {_w.F(seg.Ry)}), {_w.F(SvgTransform.Deg(seg.AngleDeg))}, {(seg.Large ? "true" : "false")}, {(seg.Sweep ? "true" : "false")}, {_w.Pt(seg.X, seg.Y)})");
                            break;
                        case SegKind.Close: _w.Checked("cvs.close_path()"); break;
                    }
                }
                break;
        }
        _w.Checked("cvs.render()");
        _w.Outdent();
        _w.Line("}");
    }
